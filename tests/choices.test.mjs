import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, readdir, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { pages } from '../site/pages.mjs';
import { renderTree } from '../workspace/choices/page.mjs';
import { buildChoices } from '../workspace/choices/build.mjs';

const source = fileURLToPath(new URL('../workspace/choices/', import.meta.url));

test('/choices/ has noindex metadata and runtime assets without links from other pages', () => {
  const output = pages();
  const html = output.get('choices/index.html');
  assert.ok(html, 'The route must be generated by the site build.');
  assert.match(html, /<link rel="canonical" href="https:\/\/zelinzhu-richard\.github\.io\/choices\/">/);
  assert.match(html, /<meta property="og:url" content="https:\/\/zelinzhu-richard\.github\.io\/choices\/">/);
  assert.match(html, /<link rel="stylesheet" href="\/choices\/style\.css">/);
  assert.match(html, /<script type="module" src="\/choices\/tree\.js"><\/script>/);
  assert.match(html, /<body class="choices-page">/);
  assert.match(html, /<header class="site-header">/);
  assert.match(html, /<meta name="robots" content="noindex, nofollow">/);
  assert.match(html, /<meta name="referrer" content="no-referrer">/);
  assert.match(html, /<meta name="description" content="A personal map of possible next steps\.">/);
  assert.doesNotMatch(html, /localhost|127\.0\.0\.1/);
  for (const [file, page] of output) {
    if (file === 'choices/index.html') continue;
    assert.doesNotMatch(page, /(?:href|src)=["'][^"']*\/choices(?:\/|[?#"'])/, file);
    assert.doesNotMatch(page, /noindex/, `Public page ${file} must remain indexable.`);
  }
});

test('the whole hierarchy remains available in the initial HTML', () => {
  const html = renderTree({
    id: 'start', title: 'Starting point', description: 'A starting description', children: [
      { id: 'study', title: 'Study further', description: 'Explore a subject', children: [
        { id: 'research', title: 'Try research', description: 'Test a question', nextStep: 'Read a paper' },
        { id: 'course', title: 'Take a course', description: 'Build a foundation', nextStep: 'Compare syllabi' },
      ] },
      { id: 'build', title: 'Build something', description: 'Make an experiment', nextStep: 'Choose a small prototype' },
    ],
  });
  for (const content of ['Starting point', 'Study further', 'Try research', 'Take a course', 'Build something', 'Read a paper', 'Compare syllabi', 'Choose a small prototype']) {
    assert.ok(html.includes(content), `Static HTML is missing ${content}`);
  }
  assert.match(html, /<ul\b/);
  assert.match(html, /<li\b[\s\S]*<ul\b[\s\S]*<li\b/);
  const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(([, id]) => id);
  assert.equal(new Set(ids).size, ids.length, 'Tree IDs must be unique.');
  const controls = [...html.matchAll(/aria-controls="([^"]+)"/g)].map(([, id]) => id);
  assert.equal(controls.length, 1, 'Only non-root nodes with children need branch toggles.');
  assert.ok(!controls.includes('children-start'), 'The root stays open so the main directions remain visible.');
  for (const id of controls) {
    assert.ok(ids.includes(id), `The branch toggle must control a real list: ${id}`);
    assert.match(html, new RegExp(`<ul\\b[^>]*id="${id}"`));
  }
  assert.equal([...html.matchAll(/aria-expanded="true"/g)].length, controls.length);
});

test('plan text is escaped at every depth, including the next step', () => {
  const html = renderTree({
    id: 'start', title: '<script>alert(1)</script>', description: 'A "quote" & a <b>tag</b>', children: [
      { id: 'leaf', title: '<img src=x onerror=alert(1)>', description: "Richard's <future>", nextStep: '<svg onload=alert(1)> & continue' },
    ],
  });
  assert.doesNotMatch(html, /<script>|<img\b|<svg onload|<b>tag<\/b>/);
  assert.ok(html.includes('&lt;script&gt;alert(1)&lt;/script&gt;'));
  assert.ok(html.includes('A &quot;quote&quot; &amp; a &lt;b&gt;tag&lt;/b&gt;'));
  assert.ok(html.includes('&lt;img src=x onerror=alert(1)&gt;'));
  assert.ok(html.includes('Richard&#39;s &lt;future&gt;'));
  assert.ok(html.includes('&lt;svg onload=alert(1)&gt; &amp; continue'));
});

test('duplicate IDs are rejected even when they occur in separate branches', () => {
  const tree = { id: 'start', title: 'Start', children: [
    { id: 'left', title: 'Left', children: [{ id: 'reused', title: 'First occurrence' }] },
    { id: 'right', title: 'Right', children: [{ id: 'reused', title: 'Second occurrence' }] },
  ] };
  assert.throws(() => renderTree(tree), /unique lowercase ids/);
});

test('missing and malformed IDs cannot produce broken controls or injected attributes', () => {
  for (const id of [undefined, null, '', 'Has-Capitals', 'two words', '1-first', 'bad" onclick="alert(1)']) {
    assert.throws(() => renderTree({ id: 'start', title: 'Start', children: [
      { id, title: 'Invalid node', children: [{ id: 'leaf', title: 'Leaf' }] },
    ] }), /unique lowercase ids/, `ID ${String(id)} must be rejected`);
  }
});

test('Choices builds only its runtime assets, excluding authoring modules and notes', async t => {
  const output = await mkdtemp(join(source, '.test-build-'));
  t.after(() => rm(output, { recursive: true, force: true }));
  await buildChoices(output);
  assert.deepEqual(await readdir(output), ['choices']);
  assert.deepEqual((await readdir(join(output, 'choices'))).sort(), ['style.css', 'tree.js']);
  for (const name of ['style.css', 'tree.js']) {
    assert.equal(await readFile(join(output, 'choices', name), 'utf8'), await readFile(join(source, name), 'utf8'));
  }
});
