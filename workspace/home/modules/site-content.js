// Exposes content.mjs to the app as #build/site-content.mjs.
// homeContent() runs here, in node, at build time; the app imports only the JSON it
// returns, so the client bundle never reaches files outside workspace/home.
// In `nuxt dev`, restart after editing content.mjs, site/content.mjs or stones/parts.mjs.
import { addTemplate, defineNuxtModule } from 'nuxt/kit';
import { homeContent } from '../content.mjs';

export default defineNuxtModule({
  meta: { name: 'site-content' },
  setup() {
    addTemplate({
      filename: 'site-content.mjs',
      getContents: () => `// Generated by modules/site-content.js from content.mjs. Do not edit.\nexport default ${JSON.stringify(homeContent(), null, 2)};\n`,
    });
  },
});
