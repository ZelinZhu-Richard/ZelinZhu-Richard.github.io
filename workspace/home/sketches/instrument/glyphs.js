export const ADVANCE = 0.78;

// Polylines for a string, centred on (0, 0): x along the line, y up, height 1.
export function strokeText(str, { tracking = 0 } = {}) {
  const chars = [...str];
  const adv = ADVANCE + tracking;
  const width = chars.length * adv - (adv - 0.6);
  const out = [];
  chars.forEach((ch, i) => {
    const g = G[ch];
    if (!g) return;
    const x0 = i * adv - width / 2;
    for (const line of g) out.push(line.map(([x, y]) => [x0 + x, y - 0.5]));
  });
  return { lines: out, width };
}
